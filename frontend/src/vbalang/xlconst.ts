export function rgbToVba(hex: string): number {
  const h = hex.replace('#', '');
  const r = parseInt(h.slice(0, 2), 16);
  const g = parseInt(h.slice(2, 4), 16);
  const b = parseInt(h.slice(4, 6), 16);
  return r + g * 256 + b * 65536;
}

export function vbaToHex(n: number): string {
  const v = n >>> 0;
  const r = v & 255;
  const g = (v >>> 8) & 255;
  const b = (v >>> 16) & 255;
  return [r, g, b].map((x) => x.toString(16).padStart(2, '0')).join('');
}

export function colorIndexToHex(i: number): string {
  const c = PALETTE[i - 1] ?? 0;
  return c.toString(16).padStart(6, '0');
}

export function hexToColorIndex(hex: string): number {
  const want = parseInt(hex.replace('#', ''), 16);
  let best = 1;
  let bd = Infinity;
  PALETTE.forEach((c, i) => {
    const d = ((c >> 16) - (want >> 16)) ** 2 + (((c >> 8) & 255) - ((want >> 8) & 255)) ** 2 + ((c & 255) - (want & 255)) ** 2;
    if (d < bd) {
      bd = d;
      best = i + 1;
    }
  });
  return best;
}
